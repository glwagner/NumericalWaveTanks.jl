#####
##### Statistically stationary turbulence for the regular-wave cases (Experiments 2 and 3).
#####
##### The flume turbulence in Experiments 2 and 3 is quasi-steady (most likely maintained by the
##### bottom boundary layer), which freely decaying box turbulence cannot mimic over the 28–45 s
##### fetch. Here the horizontal velocity fluctuations are forced at large horizontal scales:
#####
#####     F_u = γ_u ℬ[u − ⟨u⟩_xy],   F_v = γ_v ℬ[v − ⟨v⟩_xy],
#####
##### where ℬ is a band-pass filter in the horizontal wavenumber k_h ∈ [k_lo, k_hi] around the
##### energy-containing wavenumber k_e = 0.75 / L (von Kármán relation), applied with batched 2D
##### FFTs at every level, and γ_u, γ_v are gains. During the spin-up that produces a checkpoint
##### the gains are adjusted (closed loop) so that the volume rms of u and v match the case values;
##### for the paired experiment members the gains are frozen at their spin-up averages (open loop),
##### so the forcing is the same function of the flow in the wave and control members and cannot
##### mask wave-induced changes in the turbulence. The horizontal mean (k_h = 0) is never forced,
##### w is not forced (it is generated by continuity), and the surface blocking layer forms
##### naturally.
#####

using FFTW
using CUDA

include("generate_turbulence.jl")

mutable struct BandForcing{P, Q, M, W, FU, FV}
    plan :: P                 # in-place forward 2D FFT over (x, y), batched over z
    iplan :: Q                # in-place inverse
    mask :: M                 # (Nx, Ny, 1) band-pass mask, zero at k_h = 0
    work :: W                 # complex work array (Nx, Ny, Nz)
    Fu :: FU                  # forcing field for u (XFaceField)
    Fv :: FV                  # forcing field for v (YFaceField)
    γ :: Vector{Float64}      # gains for (u, v)
    I :: Vector{Float64}      # integral part of the gains (closed loop)
    targets :: Vector{Float64}
    γ_ref :: Float64
    gain :: Float64           # proportional gain (in units of γ_ref per unit relative energy error)
    κ :: Float64              # integral rate: γ_ref per unit relative energy error per second
    closed_loop :: Bool
    history :: Vector{NTuple{6, Float64}}   # (t, γu, γv, u_rms, v_rms, w_rms)
end

"""
    band_mask(grid, k_lo, k_hi)

Horizontal band-pass mask on the FFT wavenumber grid of `grid` (periodic x and y).
"""
function band_mask(grid, k_lo, k_hi)
    Nx, Ny = grid.Nx, grid.Ny
    Lx, Ly = grid.Lx, grid.Ly
    kx = 2π / Lx .* collect(fftfreq(Nx, Nx))
    ky = 2π / Ly .* collect(fftfreq(Ny, Ny))
    kh = sqrt.(reshape(kx, :, 1) .^ 2 .+ reshape(ky, 1, :) .^ 2)
    mask = Float64.((kh .>= k_lo) .& (kh .<= k_hi))
    mask[1, 1] = 0
    return reshape(mask, Nx, Ny, 1)
end

"""
    BandForcing(model; targets, k_lo, k_hi, γ=nothing, γ_ref, gain=3, κ=nothing, closed_loop=true)

Build the forcing for `model`. `targets` are the (u, v) rms to hold in closed loop; `γ` are
the initial (or frozen) gains. `γ_ref = u_rms / L` is the scale of the injection rate needed to
balance the dissipation. In closed loop the gains follow a proportional–integral law on the
relative energy error e = (target² − rms²)/target²,

    γ = max(0, γ_ref (1 + gain e) + I),   dI/dt = κ e   (κ defaults to γ_ref per eddy turnover),

with the integral frozen while the gain is clamped at zero (anti-windup); the integral term
removes the static offset a purely proportional controller leaves when the required gain differs
from γ_ref.
"""
function BandForcing(model; targets, k_lo, k_hi, γ=nothing, γ_ref, gain=3.0, κ=nothing, closed_loop=true)
    grid = model.grid
    FT = eltype(grid)
    arch = grid.architecture
    Nx, Ny, Nz = size(grid)
    work = on_architecture(arch, zeros(Complex{FT}, Nx, Ny, Nz))
    plan = plan_fft!(work, (1, 2))
    iplan = plan_ifft!(work, (1, 2))
    mask = on_architecture(arch, FT.(band_mask(grid, k_lo, k_hi)))
    Fu = XFaceField(grid)
    Fv = YFaceField(grid)
    γ₀ = isnothing(γ) ? [γ_ref, γ_ref] : collect(Float64, γ)
    κ₀ = isnothing(κ) ? Float64(γ_ref) / 10 : Float64(κ)   # generic default: γ_ref per 10 s
    return BandForcing(plan, iplan, mask, work, Fu, Fv, γ₀, zeros(2), collect(Float64, targets), Float64(γ_ref), Float64(gain),
                       κ₀, closed_loop, NTuple{6, Float64}[])
end

"Volume rms of the interior of a field (cell-count weighted, adequate for the controller)."
field_rms(f) = sqrt(sum(abs2, interior(f)) / length(interior(f)))

"""
    update_forcing!(bf::BandForcing, model; Δt=0)

Recompute the forcing fields from the current velocities and, in closed loop, the gains (the
integral part advances by `Δt`).
"""
function update_forcing!(bf::BandForcing, model; Δt=0)
    u, v, w = model.velocities
    Nz = model.grid.Nz
    for (comp, fld, F) in ((1, u, bf.Fu), (2, v, bf.Fv))
        A = interior(fld)
        bf.work .= @view A[1:size(bf.work, 1), :, 1:Nz]
        bf.plan * bf.work
        bf.work .*= bf.mask
        bf.iplan * bf.work
        interior(F)[1:size(bf.work, 1), :, 1:Nz] .= bf.γ[comp] .* real.(bf.work)
    end
    if bf.closed_loop
        for (comp, fld) in ((1, u), (2, v))
            r = field_rms(fld)
            target = bf.targets[comp]
            e = (target^2 - r^2) / target^2
            γ_unclamped = bf.γ_ref * (1 + bf.gain * e) + bf.I[comp]
            (γ_unclamped > 0 || e > 0) && (bf.I[comp] += bf.κ * e * Δt)   # anti-windup
            bf.γ[comp] = max(0.0, γ_unclamped)
        end
    end
    return nothing
end

function forcing_callback(bf::BandForcing; record_every=5)
    function callback(sim)
        update_forcing!(bf, sim.model; Δt = sim.Δt)
        if sim.model.clock.iteration % record_every == 0
            u, v, w = sim.model.velocities
            push!(bf.history, (Float64(sim.model.clock.time), bf.γ[1], bf.γ[2], field_rms(u), field_rms(v), field_rms(w)))
        end
        return nothing
    end
    return callback
end

"Forcing band for a case: [0.5, 1.5] × k_e with k_e = 0.75 / L."
function forcing_band(case; lo=0.5, hi=1.5)
    k_e = 0.75 / Float64(case.L)
    return lo * k_e, hi * k_e
end

"Reference injection rate u_rms / L; the closed-loop controller finds the actual value."
reference_gain(case) = Float64(case.u_rms) / Float64(case.L)

"""
    generate_stationary_checkpoint(; case_name, level, seed, arch, FT, Lx, Ly, spinup_eddies=16, root, overwrite=false, ...)

Spin up statistically stationary turbulence with closed-loop band forcing for
`spinup_eddies × L / u_rms` seconds and save the velocity fields together with the spin-up
averaged gains (`γ_open`) that the experiment members use in open loop.
"""
function generate_stationary_checkpoint(; case_name = "2.A.1.3",
                                          level = "R1",
                                          seed = 1,
                                          arch = GPU(),
                                          FT = Float32,
                                          Lx = 3.2,
                                          Ly = 3.2,
                                          spinup_eddies = 16.0,
                                          gain = 3.0,
                                          band = (0.5, 1.5),
                                          Δt = 0.02,
                                          numerics = "weno",
                                          root = default_data_root(),
                                          overwrite = false,
                                          progress_interval = 100)

    case = anti_stokes_case(case_name, FT)
    is_regular(case) || error("Stationary turbulence is set up for the regular-wave cases")
    path = initial_condition_path(root, case, level, seed; Lx, Ly, extra="forced")
    if isfile(path) && !overwrite
        @info "Stationary checkpoint $path already exists; skipping."
        return path
    end

    (; Nx, Ny, Nz) = level_size(level)
    Lz = Float64(case.h)
    num = numerics_settings(numerics, FT)
    grid = build_grid(arch, FT; Nx, Ny, Nz, Lx, Ly, Lz, halo=num.halo)

    # Start from the decaying-turbulence generator's field at the case rms
    Δmax = max(Lx / Nx, Ly / Ny, Lz / Nz)
    k_cut = π / (6Δmax)
    L_target = Float64(case.L)
    k_e = calibrate_k_e(Nx, Ny, Nz, Lx, Ly, Lz; L_target, k_cut, seed)
    u, v, w = spectral_velocity_field(Nx, Ny, Nz, Lx, Ly, Lz; k_e, k_cut, rng=Xoshiro(seed))
    rms(a) = sqrt(mean(abs2, a))
    u .*= Float64(case.u_rms) / rms(u); v .*= Float64(case.v_rms) / rms(v); w .*= Float64(case.w_rms) / rms(w)
    Δz = Lz / Nz
    zc_aux = [-Lz - Δz/2; [-Lz + (k - 0.5) * Δz for k in 1:Nz]; Δz/2]
    zf_aux = [-Lz + (k - 1) * Δz for k in 1:Nz+1]
    wrap_centers(a) = cat(a[:, :, end:end], a, a[:, :, 1:1]; dims=3)
    wrap_faces(a) = cat(a, a[:, :, 1:1]; dims=3)
    zc = Array(znodes(grid, Center())); zf = Array(znodes(grid, Face()))
    uᵢ = interpolate_columns(wrap_centers(u), zc_aux, zc)
    vᵢ = interpolate_columns(wrap_centers(v), zc_aux, zc)
    wᵢ = interpolate_columns(wrap_faces(w), zf_aux, zf)
    wᵢ .*= reshape(@.(tanh(-zf / 0.05) * tanh((zf + Lz) / 0.05)), 1, 1, :)
    wᵢ[:, :, 1] .= 0; wᵢ[:, :, end] .= 0

    k_lo, k_hi = band .* (0.75 / L_target)
    targets = (Float64(case.u_rms), Float64(case.v_rms))
    γ_ref = reference_gain(case)

    # Model with forcing fields (filled by the callback)
    Fu = XFaceField(grid); Fv = YFaceField(grid)
    model = NonhydrostaticModel(grid; advection=num.advection, timestepper=:RungeKutta3, closure=num.closure,
                                buoyancy=nothing, coriolis=nothing, tracers=(), forcing=(; u=Fu, v=Fv))
    bf = BandForcing(model; targets, k_lo, k_hi, γ_ref, gain, κ = γ_ref / (L_target / Float64(case.u_rms)), closed_loop=true)
    bf.Fu, bf.Fv = Fu, Fv
    set!(model; u=FT.(uᵢ), v=FT.(vᵢ), w=FT.(wᵢ))
    update_forcing!(bf, model)

    T_spin = spinup_eddies * L_target / Float64(case.u_rms)
    simulation = Simulation(model; Δt, stop_time=T_spin, verbose=false)
    simulation.callbacks[:forcing] = Callback(forcing_callback(bf), IterationInterval(1))
    wall = Ref(time_ns())
    function progress(sim)
        u, v, w = sim.model.velocities
        @info @sprintf("spin-up t = %6.2f s, rms = (%.4f, %.4f, %.4f), γ = (%.3f, %.3f), wall %s",
                       time(sim), field_rms(u), field_rms(v), field_rms(w), bf.γ[1], bf.γ[2], prettytime(1e-9 * (time_ns() - wall[])))
        wall[] = time_ns()
    end
    simulation.callbacks[:progress] = Callback(progress, IterationInterval(progress_interval))
    @info @sprintf("Spinning up stationary turbulence for %.1f s: band [%.2f, %.2f] m⁻¹, targets (%.4f, %.4f), γ_ref %.3f",
                   T_spin, k_lo, k_hi, targets..., γ_ref)
    run!(simulation)

    # Open-loop gains: average over the last eighth of the spin-up (two eddy turnovers), after the
    # controller has settled; a gain error δγ/γ shifts the open-loop equilibrium energy by 2δγ/γ
    H = bf.history
    late = filter(h -> h[1] >= 0.875T_spin, H)
    γ_open = (mean(getindex.(late, 2)), mean(getindex.(late, 3)))
    rms_late = (mean(getindex.(late, 4)), mean(getindex.(late, 5)), mean(getindex.(late, 6)))
    @info @sprintf("Stationary state: rms (%.4f, %.4f, %.4f) vs targets (%.4f, %.4f, w free); γ_open = (%.3f, %.3f)",
                   rms_late..., targets..., γ_open...)

    uf, vf, wf = model.velocities
    metadata = (; case = case_name, level, seed, Nx, Ny, Nz, Lx, Ly, Lz, FT = string(FT), forcing = "band",
                  k_lo, k_hi, band, gain, κ = bf.κ, γ_ref, γ_open, targets, T_spin, spinup_eddies, Δt, numerics,
                  rms_stationary = rms_late, rms_target = (u = case.u_rms, v = case.v_rms, w = case.w_rms),
                  history = H, amplitude = (1.0, 1.0, 1.0), L_target, k_e, k_cut,
                  oceananigans = oceananigans_version(), commit = git_commit(), created = string(now()))
    mkpath(dirname(path))
    jldsave(path; u=Array(interior(uf)), v=Array(interior(vf)), w=Array(interior(wf)), metadata)
    @info "Saved stationary checkpoint to $path"
    return path
end

"""
    stationary_forcing(model, ic_metadata)

Open-loop band forcing for an experiment member from a stationary checkpoint's metadata.
"""
function stationary_forcing(model, ic_metadata)
    return BandForcing(model; targets=ic_metadata.targets, k_lo=ic_metadata.k_lo, k_hi=ic_metadata.k_hi,
                       γ=ic_metadata.γ_open, γ_ref=ic_metadata.γ_ref, gain=ic_metadata.gain, closed_loop=false)
end

